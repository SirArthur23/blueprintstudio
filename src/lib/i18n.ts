export type TranslationKey = keyof (typeof messages)["en"];

export function t(locale: Locale, key: TranslationKey, replacements: Replacements = {}) {
  return messages[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => String(replacements[name] ?? `{${name}}`));
}

export function isLocale(value: string | null): value is Locale {
  return value === "en" || value === "de";
}

export function formatCalendarDate(timestamp: string, locale: Locale) {
  const date = new Date(timestamp);
  if (!Number.isFinite(date.getTime())) return "—";
  return new Intl.DateTimeFormat(locale === "de" ? "de-DE" : "en-GB", { timeZone: "UTC" }).format(date);
}
